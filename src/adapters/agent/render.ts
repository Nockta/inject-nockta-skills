import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { getPacksPath } from "../../packs/get-pack-path.js";
import { readSkillManifest } from "../../packs/read-skill-manifest.js";
import { mergeAgentsMd, renderStandingModeSection } from "../../core/standing-mode.js";
import { extractWhitelistedSections } from "./extract-digest.js";
import type { ResolvedPackEntry } from "../../packs/resolve-packs.js";
import type { AdapterRenderResult, RenderedFile, SkippedSkill } from "../types.js";

export interface RenderAgentOptions {
  /** Repo root to render `AGENTS.md` into. */
  targetDir: string;
  /** Packs to render — caller passes INSTALLABLE packs only (D6 gate is resolve-packs' job, not this module's). */
  packs: ResolvedPackEntry[];
  /** Override for tests; defaults to the bundled `packs/`. */
  packsRoot?: string;
  /** The D19 effective skill set (see `core/skill-selection.ts`). */
  effectiveSkills: Set<string>;
}

export type RenderAgentResult = AdapterRenderResult;

export const AGENTS_MD_RELATIVE_PATH = "AGENTS.md";

/**
 * One rendered skill's carried-forward data (AGENTS.md guidemap restructure, decisions.md
 * D<next>). Replaces the old parallel `packSections: string[]` / `packSourceBuffers: Buffer[]`
 * arrays.
 */
interface PackSkillRecord {
  skillName: string;
  /** Raw SKILL.md bytes, unmodified — whitelist extraction's input. */
  rawSkillBytes: Buffer;
  /**
   * `### <skillName>\n\n<rawSkillBytes.toString("utf8").trim()>\n`. The companion file's per-skill
   * block and the fallback digest block both reuse this string directly, never reconstructed.
   */
  renderedBlock: string;
  /**
   * This skill's `skill.json` `description` (decisions.md D26) — the digest template's per-skill
   * trigger line. Reused verbatim rather than re-parsed live from the raw SKILL.md YAML
   * frontmatter: it is the SAME text, sourced from that exact frontmatter at import time (D26),
   * never hand-authored separately — see this plan's Global Constraints for the byte-identical
   * justification. Empty string when a skill.json predates D26.
   */
  description: string;
}

function introHeader(): string {
  return (
    "# AGENTS.md\n\n" +
    "> Generated by [inject-nockta-skills](https://github.com/nockta) — Nockta-curated AI agent " +
    "guidance for this repository. Read by OpenAI Codex, Google Antigravity/`agy`, Cursor, Zed, " +
    "Windsurf, and (secondarily) GitHub Copilot.\n"
  );
}

function sha256(buffer: Buffer): string {
  return createHash("sha256").update(buffer).digest("hex");
}

/**
 * Skill-guides contents-manifest takeaway (spec "Pointer convention"): `<description>` (with a
 * trailing period added only if it doesn't already end in one) followed by the parenthetical,
 * comma-joined list of skills that actually rendered for THIS pack in THIS install, then a
 * closing period. Never caps or truncates the skill list.
 */
function buildTakeaway(description: string, skillNames: string[]): string {
  const withPeriod = description.endsWith(".") ? description : `${description}.`;
  return `${withPeriod} (${skillNames.join(", ")}).`;
}

/**
 * Generic `agent` adapter renderer (spec §8.5, decisions.md D24, D1/D19/D23/D<next>). Renders the
 * AGENTS.md guidemap: a root `AGENTS.md` (intro + standing-mode preamble + `"inline-digest"`-tier
 * inline sections + a trailing `## Skill guides` pointer index) plus one `docs/agents/<pack>.md`
 * companion file PER PACK THAT RENDERED ANYTHING — `common` included.
 *
 * `packs/<pack>/adapters/agent/<pack-name>.md` (D1 override) — when present — wins WHOLESALE over
 * BOTH of that pack's outputs: the companion file AND (for an `"inline-digest"`-tier pack) the
 * inline section. Whitelist extraction never runs against an override.
 *
 * **Agent-artifact handling (D24):** unchanged — `outputs.agent.agents` is never honored here.
 *
 * **Anti-drift invariant (decisions.md D<next>):** a companion file and its Skill-guides bullet
 * are always produced together, in the same per-pack loop iteration, from the same `packBlock`/
 * `packSkills` values — there is no code path that writes one without the other. See the spec's
 * "Background" section for the real drift bug (Grace's `coding-rules.md`) this exists to
 * structurally prevent.
 */
export function renderAgentAdapter(options: RenderAgentOptions): RenderAgentResult {
  const packsRoot = options.packsRoot ?? getPacksPath();
  const skipped: SkippedSkill[] = [];
  const sections: string[] = [];
  const skillGuidePointers: string[] = [];
  const sourceBuffers: Buffer[] = [];
  const contributingPacks: string[] = [];
  const written: RenderedFile[] = [];
  let anyOverridden = false;

  for (const pack of options.packs) {
    const packPath = join(packsRoot, pack.name);
    const overridePath = join(packPath, "adapters", "agent", `${pack.name}.md`);
    const overridden = existsSync(overridePath);

    const packSkills: PackSkillRecord[] = [];

    for (const skillName of pack.manifest.skills) {
      if (!options.effectiveSkills.has(skillName)) {
        skipped.push({
          pack: pack.name,
          skill: skillName,
          reason: "excluded by skill selection (not in the effective set, decisions.md D19)",
        });
        continue;
      }

      const skillDir = join(packPath, "skills", skillName);
      const manifest = readSkillManifest(skillDir, skillName, pack.manifest.adapters);

      if (!manifest.supportedAdapters.includes("agent")) {
        skipped.push({
          pack: pack.name,
          skill: skillName,
          reason: `adapter-restricted: supportedAdapters=[${manifest.supportedAdapters.join(", ")}] (no "agent")`,
        });
        continue;
      }

      const agentOutputs = manifest.outputs.agent;
      if (agentOutputs === false || agentOutputs === undefined || !agentOutputs.skills) {
        skipped.push({ pack: pack.name, skill: skillName, reason: "outputs.agent is false (or undeclared, or outputs.agent.skills is not true)" });
        continue;
      }

      // D24: outputs.agent.agents is never honored under this adapter.
      const raw = readFileSync(join(skillDir, "SKILL.md"));
      packSkills.push({
        skillName,
        rawSkillBytes: raw,
        renderedBlock: `### ${skillName}\n\n${raw.toString("utf8").trim()}\n`,
        description: manifest.description ?? "",
      });
    }

    let packBlock: string | null = null;
    let overrideBuf: Buffer | null = null;
    if (overridden) {
      overrideBuf = readFileSync(overridePath);
      packBlock = `${overrideBuf.toString("utf8").trim()}\n`;
      anyOverridden = true;
    } else if (packSkills.length > 0) {
      packBlock = `## ${pack.manifest.displayName}\n\n${pack.manifest.description}\n\n${packSkills.map((r) => r.renderedBlock).join("\n")}`;
    }

    if (!packBlock) continue; // nothing rendered for this pack — no file, no bullet, no inline section.

    // Step 1 (spec "Per-pack loop"): the companion file — unconditional, every tier, every pack.
    const companionRelativePath = `docs/agents/${pack.name}.md`;
    const companionOutputPath = join(options.targetDir, companionRelativePath);
    mkdirSync(dirname(companionOutputPath), { recursive: true });
    const companionContent = Buffer.from(packBlock, "utf8");
    writeFileSync(companionOutputPath, companionContent);
    const companionSourceHash = overridden
      ? sha256(overrideBuf as Buffer)
      : sha256(Buffer.concat(packSkills.map((r) => r.rawSkillBytes)));
    written.push({
      relativePath: companionRelativePath,
      outputPath: companionOutputPath,
      sourcePath: overridden ? overridePath : join(packPath, "skills"),
      overridden,
      adapter: "agent",
      pack: pack.name,
      kind: "instructions",
      content: companionContent,
      sourceContentHash: companionSourceHash,
    });

    // Step 2: the Skill-guides bullet — unconditional, every tier, every pack. Takeaway is built
    // from the PRE-OVERRIDE rendered-skill-name list (packSkills is populated by the gating pass
    // above regardless of whether this pack is overridden).
    const skillNames = packSkills.map((r) => r.skillName);
    const takeaway = buildTakeaway(pack.manifest.description, skillNames);
    skillGuidePointers.push(`- docs/agents/${pack.name}.md — ${takeaway} ${pack.manifest.agentTrigger}`);
    contributingPacks.push(pack.name);

    // Step 3: ONLY "inline-digest"-tier packs additionally build the inline AGENTS.md section.
    if (pack.manifest.tier === "inline-digest") {
      let inlineBlock: string;
      let inlineSourceBuffer: Buffer;
      if (overridden) {
        // Same bytes as the companion file — override wins wholesale, extraction never runs.
        inlineBlock = packBlock;
        inlineSourceBuffer = overrideBuf as Buffer;
      } else {
        const digestSkillBlocks = packSkills.map((r) => {
          const matched = extractWhitelistedSections(r.rawSkillBytes.toString("utf8"));
          if (matched.length === 0) return r.renderedBlock; // fallback: full body, unchanged.
          return `### ${r.skillName}\n\n**${r.description}**\n\n${matched.join("\n\n")}\n`;
        });
        inlineBlock = `## ${pack.manifest.displayName}\n\n${pack.manifest.description}\n\n${digestSkillBlocks.join("\n")}`;
        inlineSourceBuffer = Buffer.from(digestSkillBlocks.join("\n"), "utf8");
      }
      sections.push(inlineBlock);
      sourceBuffers.push(inlineSourceBuffer);
    } else {
      // "companion"-tier: a small deterministic buffer still feeds AGENTS.md's own hash, since
      // this pack's Skill-guides bullet text (which DOES change AGENTS.md's rendered bytes) must
      // be reflected in the staleness fingerprint even though no body content is inlined.
      sourceBuffers.push(
        Buffer.from(
          `${pack.name}\n${pack.manifest.description}\n${pack.manifest.agentTrigger}\n${[...skillNames].sort().join(",")}`,
          "utf8",
        ),
      );
    }
  }

  if (skillGuidePointers.length === 0) {
    return { written: [], skipped };
  }

  // Standing-mode contract (decisions.md D34) is the PREAMBLE; `## Skill guides` is the new TAIL,
  // immediately before the closing guard-region marker `mergeAgentsMd()` adds.
  const body =
    `${introHeader()}\n${renderStandingModeSection()}\n\n${sections.join("\n")}` +
    (skillGuidePointers.length > 0 ? `\n\n## Skill guides\n\n${skillGuidePointers.join("\n")}\n` : "");
  const sourceContentHash = sha256(Buffer.concat(sourceBuffers));

  const outputPath = join(options.targetDir, "AGENTS.md");
  mkdirSync(dirname(outputPath), { recursive: true });
  const existing = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : null;
  const merged = mergeAgentsMd(existing, body);
  writeFileSync(outputPath, Buffer.from(merged.content, "utf8"));

  const content = Buffer.from(mergeAgentsMd(null, body).content, "utf8");

  written.push({
    relativePath: AGENTS_MD_RELATIVE_PATH,
    outputPath,
    sourcePath: packsRoot,
    overridden: anyOverridden,
    adapter: "agent",
    pack: [...contributingPacks].sort().join(","),
    kind: "instructions",
    content,
    sourceContentHash,
    mergedIntoConsumerContent: merged.hadConsumerContent,
  });

  return { written, skipped };
}
